#!/usr/bin/env python3
"""Load the legitimate-offer sample into the VKG.

Reads   data/real/legit_offers.csv: job advertisements captured from job boards, with a note on
        whether the employer could be verified in public sources.
Writes  db/15_legit_offers.sql
        the M-Legit-* mappings inside mappings/ramona.obda (replaced if already there)

Each advertisement becomes a :JobOffer offered by an :Employer whose :hasVerifiedIdentity says
whether the employer was verified, documented in an :EvidenceSource that is the job-board posting,
and carrying the same Type A and Type B red flags the press-documented offers carry, so that the
two corpora can be compared with one query. No term is added to the ontology.

An employer counts as verified when the capture notes it as a known brand or as found to exist in
public sources. Borderline cases and employers that were not found are loaded as not verified.

Usage: python3 scripts/build_legit_offers_module.py
"""
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data/real/legit_offers.csv"
SQL = ROOT / "db/15_legit_offers.sql"
OBDA = ROOT / "mappings/ramona.obda"
D = "https://w3id.org/ratr-o/data"

# job board named in the capture -> platform_name in ramona.platforms
BOARD = {"linkedin": "LinkedIn", "talenteca": "Talenteca", "occ": "OCC Mundial",
         "indeed": "Indeed", "computrabajo": "CompuTrabajo"}
NEW_PLATFORMS = [("LinkedIn", "classifieds"), ("Talenteca", "classifieds")]


def q(v):
    return "NULL" if v in (None, "") else "'" + str(v).replace("'", "''") + "'"


def verified(note):
    n = note.strip().lower()
    return n.startswith("marca_conocida") or n.startswith("existe")


def url(v):
    """The capture writes '(sin liga)' when the posting had no stable link."""
    v = v.strip()
    return v if v.lower().startswith("http") else ""


def board(fuente):
    key = re.split(r"[\s(]", fuente.strip().lower())[0]
    return BOARD[key]


def build_sql():
    rows = list(csv.DictReader(SRC.open(encoding="utf-8")))
    L = ["-- Legitimate-offer sample: job advertisements captured from job boards (data/real/legit_offers.csv).",
         "-- GENERATED by scripts/build_legit_offers_module.py. Do not edit by hand.",
         "SET search_path TO ramona, public;", "",
         "INSERT INTO platforms (platform_name, platform_type, platform_country) VALUES\n" + ",\n".join(
             f" ({q(n)}, {q(t)}, NULL)" for n, t in NEW_PLATFORMS) + "\nON CONFLICT (platform_name) DO NOTHING;", "",
         "CREATE TABLE IF NOT EXISTS legit_offers (",
         "    legit_id TEXT PRIMARY KEY, employer_name TEXT NOT NULL, employer_verified BOOLEAN NOT NULL,",
         "    verification_basis TEXT NOT NULL, job_title TEXT NOT NULL, category TEXT, offer_location TEXT,",
         "    weekly_mxn NUMERIC(14,2), country_code CHAR(2) NOT NULL REFERENCES countries(country_code),",
         "    platform_id INTEGER NOT NULL REFERENCES platforms(platform_id), posting_url TEXT,",
         "    board TEXT NOT NULL, captured_on DATE NOT NULL);",
         "CREATE TABLE IF NOT EXISTS legit_offer_flags (",
         "    legit_id TEXT REFERENCES legit_offers(legit_id), flag TEXT NOT NULL, track CHAR(1) NOT NULL CHECK (track IN ('A','B')),",
         "    PRIMARY KEY (legit_id, flag));", ""]
    out, flags = [], []
    for r in rows:
        b = board(r["fuente"])
        out.append(
            f" ({q(r['legit_id'])}, {q(r['empresa'].strip())}, {'TRUE' if verified(r['verificacion_empresa']) else 'FALSE'}, "
            f"{q(r['verificacion_empresa'].strip())}, {q(r['puesto'].strip())}, {q(r['categoria'].strip())}, {q(r['ubicacion'].strip())}, "
            f"{r['sueldo_semanal_mxn_equiv'].strip() or 'NULL'}, (SELECT country_code FROM countries WHERE country_iso3 = 'MEX'), "
            f"(SELECT platform_id FROM platforms WHERE platform_name = {q(b)}), {q(url(r['url_linkedin']))}, {q(b)}, "
            f"DATE {q(r['fecha_captura'].strip())})")
        for track, col in (("A", "type_a_flags"), ("B", "type_b_flags")):
            for f_ in filter(None, (x.strip() for x in re.split(r"[;,]", r[col]))):
                flags.append(f" ({q(r['legit_id'])}, {q(f_)}, '{track}')")
    L.append("INSERT INTO legit_offers VALUES\n" + ",\n".join(out) + "\nON CONFLICT DO NOTHING;\n")
    L.append("INSERT INTO legit_offer_flags VALUES\n" + ",\n".join(flags) + "\nON CONFLICT DO NOTHING;\n")
    SQL.write_text("\n".join(L), encoding="utf-8")
    return len(rows), sum(1 for r in rows if verified(r["verificacion_empresa"])), len(flags)


def m(mid, target, source):
    return f"mappingId   {mid}\ntarget      {target}\nsource      {source}\n"


def build_obda():
    o = f"<{D}/legit-offer/{{legit_id}}>"
    e = f"<{D}/legit-offer/{{legit_id}}/employer>"
    p = f"<{D}/legit-offer/{{legit_id}}/posting>"
    fl = f"<{D}/legit-offer/{{legit_id}}/flag/{{flag}}>"
    T, F = "ramona.legit_offers", "ramona.legit_offer_flags"
    B = [
        m("M-Legit-Offer", f"{o} a :JobOffer ; :offeredRole {{job_title}}^^xsd:string ; :offeredByEmployer {e} ; :offerDocumentedIn {p} .",
          f"SELECT legit_id, job_title FROM {T}"),
        m("M-Legit-Country", f"{o} :inCountry <{D}/country/{{country_iso3}}> .",
          f"SELECT l.legit_id, c.country_iso3 FROM {T} l JOIN ramona.countries c ON c.country_code = l.country_code"),
        m("M-Legit-Location", f"{o} :offeredLocation {{offer_location}}^^xsd:string .", f"SELECT legit_id, offer_location FROM {T} WHERE offer_location IS NOT NULL"),
        m("M-Legit-WeeklyMXN", f"{o} :offeredSalaryMXN {{weekly_mxn}}^^xsd:decimal .", f"SELECT legit_id, weekly_mxn FROM {T} WHERE weekly_mxn IS NOT NULL"),
        m("M-Legit-Platform", f"{o} :postedVia <{D}/platform/{{platform_id}}> .", f"SELECT legit_id, platform_id FROM {T}"),
        m("M-Legit-Employer", f"{e} a :Employer ; :agentName {{employer_name}}^^xsd:string ; :hasVerifiedIdentity {{employer_verified}}^^xsd:boolean .",
          f"SELECT legit_id, employer_name, employer_verified FROM {T}"),
        m("M-Legit-Posting", f"{p} a :EvidenceSource ; :sourceOutlet {{board}}^^xsd:string ; :sourceKind {{source_kind}}^^xsd:string .",
          f"SELECT legit_id, board, 'job_board_posting' AS source_kind FROM {T}"),
        m("M-Legit-PostingUrl", f"{p} :sourceUrl {{posting_url}}^^xsd:anyURI .", f"SELECT legit_id, posting_url FROM {T} WHERE posting_url IS NOT NULL"),
        m("M-Legit-Flag", f"{o} :hasRedFlag {fl} .", f"SELECT legit_id, flag FROM {F}"),
        m("M-Legit-FlagType", f"{fl} :flagType {{flag}}^^xsd:string .", f"SELECT legit_id, flag FROM {F}"),
        m("M-Legit-FlagA", f"{fl} a :ClassicRedFlag .", f"SELECT legit_id, flag FROM {F} WHERE track = 'A'"),
        m("M-Legit-FlagB", f"{fl} a :CredibleLethalRedFlag .", f"SELECT legit_id, flag FROM {F} WHERE track = 'B'"),
    ]
    text = OBDA.read_text(encoding="utf-8")
    text = re.sub(r"mappingId\s+M-Legit-[^\n]*\ntarget[^\n]*\nsource[^\n]*\n\n?", "", text)
    i = text.rstrip().rfind("]]")
    OBDA.write_text(text[:i].rstrip() + "\n\n" + "\n".join(B) + "\n]]\n", encoding="utf-8")
    return len(B)


if __name__ == "__main__":
    n, v, f = build_sql()
    print(f"SQL: {n} advertisements, {v} with a verified employer, {f} flags -> {SQL.relative_to(ROOT)}")
    print(f"OBDA: {build_obda()} M-Legit-* mappings -> {OBDA.relative_to(ROOT)}")
