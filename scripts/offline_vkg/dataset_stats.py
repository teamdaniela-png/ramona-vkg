#!/usr/bin/env python3
"""Write docs/DATASET_STATS.md from the SQLite copy of the seeds and the ontology.

    python3 scripts/offline_vkg/dataset_stats.py <ramona.db> <abox.ttl>

Both files are produced by scripts/offline_vkg/run_all.sh in its work directory.
"""
import os
import sqlite3
import sys

import rdflib
from rdflib import OWL, RDF

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
NS = "https://w3id.org/ratr-o#"
con = sqlite3.connect(sys.argv[1])
abox = rdflib.Graph().parse(sys.argv[2])
tbox = rdflib.Graph().parse(os.path.join(ROOT, "ontology/ratr-o.ttl"))


def n(sql):
    return con.execute(sql).fetchone()[0]


def own(kind):
    return sum(1 for s in tbox.subjects(RDF.type, kind) if str(s).startswith(NS))


version = next(tbox.objects(None, OWL.versionInfo))
rows = [
    ("Job offers anchored to a press article or a documented case", n("SELECT COUNT(*) FROM offers"),
     "`db/03_seed_cases.sql`, `db/05_seed_cases_v1_2.sql`"),
    ("Offer descriptions documented in the press, verified against the source text", n("SELECT COUNT(*) FROM press_offers"),
     "`db/12_press_offers_real.sql`, from `data/real/press_offers_verified.csv`"),
    ("Press articles documenting those offers", n("SELECT COUNT(*) FROM press_articles"), "`db/12_press_offers_real.sql`"),
    ("Postings captured from formal job boards", n("SELECT COUNT(*) FROM legit_offers"),
     "`db/15_legit_offers.sql`, from `data/real/legit_offers.csv`"),
    ("of which, employer verified in public sources", n("SELECT COUNT(*) FROM legit_offers WHERE employer_verified"), ""),
    ("Evidence sources", n("SELECT COUNT(*) FROM evidence_sources"), "`db/02_seed_reference.sql`, `db/05_seed_cases_v1_2.sql`"),
    ("Recruiters (pseudonymous identifiers)", n("SELECT COUNT(*) FROM recruiters"), "`db/03_seed_cases.sql`, `db/05_seed_cases_v1_2.sql`"),
    ("Documented patterns", n("SELECT COUNT(*) FROM survivor_patterns"), "`db/02_seed_reference.sql`, `db/07_press_patterns.sql`, `db/10_deep_patterns.sql`"),
    ("Fraud-scheme exemplars", n("SELECT COUNT(*) FROM fraudscheme_exemplars"), "`db/09_fraudscheme_examples.sql`"),
    ("Trafficking routes", n("SELECT COUNT(*) FROM trafficking_routes"), "`db/02_seed_reference.sql`, `db/06_ctdc_routes.sql`"),
    ("of which, with a CTDC victim count (three victims or more)", n("SELECT COUNT(*) FROM route_victim_counts"), "`db/14_route_victim_counts.sql`"),
    ("Countries (ISO 3166-1)", n("SELECT COUNT(*) FROM countries"), "`db/08_enriched_countries.sql`"),
    ("of which, attested in CTDC", n("SELECT COUNT(*) FROM countries WHERE attested_in_ctdc"), ""),
    ("Social-media items, synthetic", n("SELECT COUNT(*) FROM social_items"), "`db/11_social_media_module.sql`, from `data/synthetic/`"),
    ("Lexicon terms (El Colegio de México, 2025)", n("SELECT COUNT(*) FROM lexicon_terms"), "`db/11_social_media_module.sql`, from `data/lexicon/`"),
]
L = ["# Dataset statistics", "",
     "Generated by `scripts/offline_vkg/dataset_stats.py` from the seed files in `db/` and RATR-O %s." % version, "",
     "## Ontology", "",
     "| | |", "|---|---:|",
     "| Classes | %d |" % own(OWL.Class),
     "| Object properties | %d |" % own(OWL.ObjectProperty),
     "| Datatype properties | %d |" % own(OWL.DatatypeProperty),
     "| Triples | {:,} |".format(len(tbox)), "",
     "## What a clone of the repository loads", "",
     "| | Rows | Seed file |", "|---|---:|---|"]
L += ["| %s | %s | %s |" % (a, "{:,}".format(b), c) for a, b, c in rows]
L += ["", "The graph the mappings produce over these seeds has {:,} triples.".format(len(abox)), "",
      "## With the CTDC release", "",
      "The CTDC Global Synthetic Dataset v2025 (IOM and partners, CC BY 4.0) has 257,969 victim records. It is not",
      "redistributed here; `scripts/ingest_ctdc.py` loads a downloaded copy into the victim tables.", "",
      "## With the UNODC release", "",
      "The UNODC data portal publishes the figures on trafficking in persons that Member States report: 65,398",
      "figures for 198 countries, 2003 to 2023, in the release of 28 October 2025. It is not redistributed here;",
      "`scripts/ingest_unodc.py` loads a downloaded copy into `ramona.unodc_statistics`.", "",
      "## The twenty routes with most victims in CTDC", "",
      "| Origin | Destination | Victims |", "|---|---|---:|"]
for o, d, c in con.execute(
        "SELECT a.country_name, b.country_name, r.victim_count FROM route_victim_counts r "
        "JOIN countries a ON a.country_iso3 = r.origin_country JOIN countries b ON b.country_iso3 = r.destination_country "
        "ORDER BY r.victim_count DESC, a.country_name, b.country_name LIMIT 20"):
    L.append("| %s | %s | %s |" % (o, d, "{:,}".format(c)))
L += ["", "Results over the documented offers are in `docs/results/`. The provenance of every figure is in",
      "`docs/RIGOR_STATEMENT.md`."]
open(os.path.join(ROOT, "docs/DATASET_STATS.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("wrote docs/DATASET_STATS.md")
