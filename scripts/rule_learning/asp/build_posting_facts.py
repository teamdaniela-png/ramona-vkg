#!/usr/bin/env python3
"""Write job-board postings collected by the domain expert as ASP facts.

Reads every data/operational/private/anuncios_*.csv (not published) and writes one .lp file next
to each. The columns are the ones the expert rules ask about.
"""
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PRIVATE = ROOT / "data/operational/private"
HIGH_PAY_MONTHLY = 20000   # set by the domain expert: ordinary postings pay 8,000 to 10,000 a month
OPERATIONAL = re.compile(r"doblador|empacador|picker|garrotero|ayudante|auxiliar|almac[eé]n|limpieza|lavaloza|cargador|repartidor|surtidor|acomodador|cajer|atenci[oó]n a(l)? ?client|empleado general|dependient|meser|vendedor de piso|call center|asesor telef[oó]nico|ejecutivo telef[oó]nico", re.I)
PERSONAL_CONTACT = {"whatsapp", "correo_gmail", "correo_hotmail", "mensaje_privado", "telefono"}
SECURITY = re.compile(r"guardia|vigilan|seguridad|custodi|escolta", re.I)
PROMOTION = re.compile(r"promotor|demostrador|promotor[ií]a|vendedor|ventas", re.I)
SPECIALISED = re.compile(r"\bphd\b|doctorado|doctor en|cient[ií]fic[oa] de datos|data scientist|machine learning|inteligencia artificial|\bia\b|\bai\b|matem[aá]tic|computer science|ciencias de la computaci[oó]n|investigador", re.I)
# Jobs the Consejo Ciudadano (6to Reporte de Trata de Personas) lists as the false offers used to hook victims.
TRAFFICKING_RISK = re.compile(r"meser|recepcionist|masajist|mucama|dom[eé]stic|ni[nñ]er|cuidador|entretenimiento para adultos|table dance|bailarina", re.I)
ANONYMOUS = re.compile(r"confidencial|oculto|sin empresa|an[oó]nim|sin nombre", re.I)
APPEARANCE = re.compile(r"(buena|excelente) presentaci", re.I)
FLAGS = (("ventas", "sales"), ("temporada", "seasonal"), ("becario", "internship"),
         ("entry_level", "entry_level"), ("marca_conocida", "large_verified_employer"))


def main():
    for path in sorted(PRIVATE.glob("anuncios_*.csv")):
        lines = ["% Generated by scripts/rule_learning/asp/build_posting_facts.py. Do not edit."]
        for r in csv.DictReader(open(path, encoding="utf-8")):
            o = r["id"].lower().replace("-", "_")
            lines.append(f"offer({o}). job_board_posting({o}).")
            if r["sueldo_max_mensual"] and float(r["sueldo_max_mensual"]) >= HIGH_PAY_MONTHLY:
                lines.append(f"high_pay({o}).")
            if r["urgente"] == "1":
                lines.append(f"has({o}, contratacion_urgente).")
            if r["experiencia"] == "sin_experiencia":
                lines.append(f"has({o}, sin_experiencia).")
            if r["experiencia"] == "requerida":
                lines.append(f"requires_experience({o}).")
            lines += [f"{p}({o})." for c, p in FLAGS if r[c] == "1"]
            if r["ventas"] != "1" and PROMOTION.search(r["puesto"]):
                lines.append(f"sales({o}).")
            if SPECIALISED.search(r["puesto"]):
                lines.append(f"specialised_role({o}).")
            if SECURITY.search(r["puesto"]):
                lines.append(f"security({o}).")
            if OPERATIONAL.search(r["puesto"]):
                lines.append(f"operational_role({o}).")
            if r["contacto"] in PERSONAL_CONTACT:
                lines.append(f"personal_contact({o}).")
            if r.get("verificacion") in ("existe", "marca_conocida"):
                lines.append(f"employer_verified({o}).")
            if r.get("no_solicitado") == "1":
                lines.append(f"unsolicited_contact({o}).")
            if r.get("usa_nombre_ajeno") == "1":
                lines.append(f"borrowed_name({o}).")
            if r.get("otro_estado_o_traslado") == "1":
                lines.append(f"relocation({o}).")
            if r.get("puesto_real_distinto") == "1":
                lines.append(f"different_job({o}).")
            for s in filter(None, (r.get("senales_validacion") or "").split(";")):
                lines.append(f"validation_signal({o}, {s}).")
            if r.get("pide_dinero") == "1":
                lines.append(f"asks_for_money({o}).")
            if r["puesto"].startswith("Sin puesto"):
                lines.append(f"no_job_described({o}).")
            if TRAFFICKING_RISK.search(r["puesto"]):
                lines.append(f"trafficking_risk_role({o}).")
            if ANONYMOUS.search(r["empresa"]):
                lines.append(f"anonymous_employer({o}).")
            if APPEARANCE.search(r["puesto"] + " " + (r.get("nota") or "")):
                lines.append(f"appearance_required({o}).")
            if r.get("pide_documentos") == "1":
                lines.append(f"asks_for_documents({o}).")
            if r.get("pide_descargar") == "1":
                lines.append(f"asks_to_download({o}).")
            if r.get("intermediaria") == "1":
                lines.append(f"intermediary({o}).")
            if r["id"].startswith("D-"):
                lines.append(f"expert_doubtful({o}).")
        out = path.with_suffix(".lp")
        out.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"wrote {out.name}: {len(lines) - 1} facts")


if __name__ == "__main__":
    main()
