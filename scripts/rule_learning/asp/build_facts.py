#!/usr/bin/env python3
"""Write the documented offers and the verified postings as ASP facts (offers.lp).

Scope: press-documented offers in Mexico (audit status "verificada") and postings of verified employers.
Reads data/processed/rule_learning/examples.csv (run learn_rules.py first) and the press table for the outcome.
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
EX = ROOT / "data/processed/rule_learning/examples.csv"
PRESS = ROOT / "data/real/press_offers_verified.csv"
OUT = ROOT / "data/processed/rule_learning/offers.lp"

FLAGS = ["sueldo_alto", "empleo_fuera_estado", "pago_adelantado", "horario_flexible", "traslado_pagado",
         "sin_experiencia", "contratacion_urgente", "rol_plausible_gancho", "pidio_datos_personales",
         "cita_edificio_multiusos", "empresa_sin_nombre", "pidio_ir_sola", "pidio_sin_identificacion",
         "whatsapp_sin_logo", "messenger_a_whatsapp", "cambio_ubicacion_ultimo_momento"]
JOBS = {"job_security": "security", "job_driver": "driver", "job_service": "service",
        "job_care_cleaning": "care_cleaning", "job_field_construction": "field_construction",
        "job_remote_tasks": "remote_tasks"}
TARGETS = {"target_women": "women", "target_minors": "minors", "target_young": "young"}
KIND = {"fraude_economico": "fraud", "explotacion_sexual": "sexual", "explotacion_laboral": "labour",
        "desaparicion": "disappearance", "homicidio": "homicide", "rescate": "rescue",
        "detencion_reclutador": "recruiter_arrested", "other": "other", "": "unknown"}


def atom(i):
    return i.lower().replace("-", "_")


def main():
    press = {r["offer_uid"]: r for r in csv.DictReader(open(PRESS, encoding="utf-8"))}
    lines = ["% Generated by scripts/rule_learning/asp/build_facts.py. Do not edit."]
    n = 0
    for r in csv.DictReader(open(EX, encoding="utf-8")):
        if r["source"] == "press" and r["mexico"] != "1":
            continue
        if r["source"] == "legit" and r["verified_employer"] != "1":
            continue
        o = atom(r["id"])
        n += 1
        lines.append(f"offer({o}).")
        if r["source"] == "press":
            p = press[r["id"]]
            kind = "criminal" if p["criminal_recruitment"] == "True" else KIND[p["outcome"]]
            lines.append(f"documented_trap({o}). kind({o}, {kind}).")
        else:
            lines.append(f"verified_posting({o}).")
        lines += [f"has({o}, {f})." for f in FLAGS if r[f] == "1"]
        lines += [f"{v}({o})." for k, v in JOBS.items() if r[k] == "1"]
        lines += [f"target({o}, {v})." for k, v in TARGETS.items() if r[k] == "1"]
        if r["pay_weekly_over_1_5x_verified_median"] == "1":
            lines.append(f"high_pay({o}).")
        if r["requirements_stated"] == "1":
            lines.append(f"requirements({o}).")
        if r["via_social_or_messaging"] == "1":
            lines.append(f"social_channel({o}).")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {n} offers, {len(lines) - 1} lines")


if __name__ == "__main__":
    main()
