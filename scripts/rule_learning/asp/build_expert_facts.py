#!/usr/bin/env python3
"""Write the extra facts the expert rules need (expert_facts.lp).

Adds, for the offers of offers.lp, what the expert rules ask about and the flags do not carry:
whether the offer asks for experience, whether it is a sales or a seasonal job, an entry-level
post or an internship, whether the employer is a known brand, and whether the offer arrived by
WhatsApp, message or e-mail without the person having asked for it. Each is read from the text of the offer with the patterns below.
Run after build_facts.py.
"""
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PRESS = ROOT / "data/real/press_offers_verified.csv"
LEGIT = ROOT / "data/real/legit_offers.csv"
FACTS = ROOT / "data/processed/rule_learning/offers.lp"
OUT = ROOT / "data/processed/rule_learning/expert_facts.lp"

NO_EXPERIENCE = re.compile(r"sin (necesidad de )?experiencia|no (se )?(requiere[n]?|necesita|ocupa) experiencia|con o sin experiencia", re.I)
EXPERIENCE = re.compile(r"experiencia", re.I)
SALES = re.compile(r"\bventas?\b|vendedor|promotor", re.I)
SEASONAL = re.compile(r"temporada|navide|eventual|verano", re.I)
INTERNSHIP = re.compile(r"becari|practicante|pasante", re.I)
ENTRY_LEVEL = re.compile(r"entry[ -]level|trainee|aprendiz|junior", re.I)
# Operational posts: folding, packing, serving customers, charging at the till and the like,
# for which an employer hires quickly and without experience.
OPERATIONAL = re.compile(r"doblador|empacador|picker|garrotero|ayudante|auxiliar|almac[eé]n|limpieza|lavaloza|cargador|repartidor|surtidor|acomodador|cajer|atenci[oó]n a(l)? ?client|empleado general|dependient|meser|vendedor de piso|call center|asesor telef[oó]nico|ejecutivo telef[oó]nico", re.I)
WHATSAPP_OR_MAIL = re.compile(r"whats|correo|e-?mail|gmail|hotmail|sms|mensaje", re.I)
# Contact through a personal channel instead of the employer's own.
PERSONAL = re.compile(r"whats|gmail|hotmail|mensaje privado|inbox|messenger|telegram", re.I)
# The source says in so many words that the person had not asked for the contact.
UNSOLICITED = re.compile(r"no solicitad|aleatori", re.I)


def atom(i):
    return i.lower().replace("-", "_")


def main():
    offers = set(re.findall(r"^offer\((\w+)\)\.", FACTS.read_text(encoding="utf-8"), re.M))
    lines = ["% Generated by scripts/rule_learning/asp/build_expert_facts.py. Do not edit."]
    rows = []
    for r in csv.DictReader(open(PRESS, encoding="utf-8")):
        rows.append((atom(r["offer_uid"]), r["job_title"], r["requirements"],
                     r["job_title"] + " " + r["paraphrase"], r["contact_method"] + " " + r["platform"], False))
    for r in csv.DictReader(open(LEGIT, encoding="utf-8")):
        rows.append((atom(r["legit_id"]), r["puesto"], r["requisitos"], r["puesto"] + " " + r["notas"],
                     r["como_postular"], r["verificacion_empresa"].startswith("marca_conocida")))
    for o, title, requirements, text, contact, known_brand in rows:
        if o not in offers:
            continue
        if EXPERIENCE.search(requirements) and not NO_EXPERIENCE.search(requirements):
            lines.append(f"requires_experience({o}).")
        if SALES.search(title):
            lines.append(f"sales({o}).")
        if SEASONAL.search(text):
            lines.append(f"seasonal({o}).")
        if INTERNSHIP.search(title):
            lines.append(f"internship({o}).")
        if ENTRY_LEVEL.search(title):
            lines.append(f"entry_level({o}).")
        if OPERATIONAL.search(title):
            lines.append(f"operational_role({o}).")
        if known_brand:
            lines.append(f"large_verified_employer({o}).")
        if WHATSAPP_OR_MAIL.search(contact) and UNSOLICITED.search(contact):
            lines.append(f"unsolicited_contact({o}).")
        if PERSONAL.search(contact):
            lines.append(f"personal_contact({o}).")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(lines) - 1} facts")


if __name__ == "__main__":
    main()
