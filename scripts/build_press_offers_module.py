#!/usr/bin/env python3
"""
Carga el corpus REAL de ofertas de prensa al VKG (RATR-O v1.10).

Lee  data/real/press_offers_verified.csv (solo audit_status = verificada), data/real/press_offer_sources.csv
Escribe db/12_press_offers_real.sql
        los mapeos M-Press-* dentro de mappings/ramona.obda (los reemplaza si ya existen)

Uso: python3 scripts/build_press_offers_module.py   (correr despues de build_real_offers.py)
"""
import csv
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OFFERS = ROOT / "data/real/press_offers_verified.csv"  # solo se cargan las de audit_status = verificada
SOURCES = ROOT / "data/real/press_offer_sources.csv"
SQL = ROOT / "db/12_press_offers_real.sql"
OBDA = ROOT / "mappings/ramona.obda"
D = "https://w3id.org/ratr-o/data"

TYPE_A = "sueldo_alto sin_experiencia contratacion_urgente pago_adelantado traslado_pagado horario_flexible empleo_fuera_estado".split()
TYPE_B = ("empresa_sin_nombre whatsapp_sin_logo cita_edificio_multiusos pidio_ir_sola pidio_sin_identificacion "
          "messenger_a_whatsapp horario_atipico pidio_datos_personales rol_plausible_gancho cambio_ubicacion_ultimo_momento").split()
SCHEMES = ("IdentityTheftScheme PyramidScheme PayToWorkScheme VisaFraudScheme InPersonLureScheme DebtBondageTraffickingScheme "
           "DomesticWorkerLockInScheme OnlineCryptoJobScheme ModelingAgencyScheme CallCenterScamScheme FakeMaquilaScheme "
           "MLMHealthBeautyScheme GigEconomyFakeDriverScheme ForcedCriminalityScheme OnlineInfluencerSalesScheme "
           "ForeignLanguageTeacherScheme ChildRecruitmentCriminalScheme CentralAmericanMigrantLabourScheme "
           "AgriculturalBondageScheme ConstructionLabourBondageScheme").split()
# plataforma de la nota -> platform_name en ramona.platforms (None = no es una plataforma)
PLATFORM = {"facebook": "Facebook", "instagram": "Instagram", "whatsapp": "WhatsApp", "tiktok": "TikTok",
            "telegram": "Telegram", "computrabajo": "CompuTrabajo", "occ": "OCC Mundial", "indeed": "Indeed"}
NEW_PLATFORMS = [("Facebook", "facebook"), ("Instagram", "instagram"), ("Indeed", "classifieds")]


def q(v):
    return "NULL" if v in (None, "") else "'" + str(v).replace("'", "''") + "'"


def akey(url):
    return hashlib.sha1(url.encode()).hexdigest()[:12]


def build_sql():
    offers = [o for o in csv.DictReader(open(OFFERS, encoding="utf-8")) if o["audit_status"] == "verificada"]
    keep = {o["offer_uid"] for o in offers}
    sources = [s for s in csv.DictReader(open(SOURCES, encoding="utf-8")) if s["offer_uid"] in keep]
    L = ["-- RATR-O v1.10: REAL offers described in press articles (data/real/press_offers.csv).",
         "-- GENERATED by scripts/build_press_offers_module.py. Do not edit by hand.",
         "SET search_path TO ramona, public;", "",
         "INSERT INTO platforms (platform_name, platform_type, platform_country) VALUES",
         ",\n".join(f" ({q(n)}, {q(t)}, NULL)" for n, t in NEW_PLATFORMS) + "\nON CONFLICT (platform_name) DO NOTHING;", "",
         "CREATE TABLE IF NOT EXISTS press_articles (",
         "    article_key TEXT PRIMARY KEY, url TEXT NOT NULL, outlet TEXT, published TEXT);",
         "CREATE TABLE IF NOT EXISTS press_offers (",
         "    offer_uid TEXT PRIMARY KEY, country_code CHAR(2) REFERENCES countries(country_code),",
         "    platform_id INTEGER REFERENCES platforms(platform_id), job_title TEXT, pay_amount NUMERIC(14,2),",
         "    pay_currency TEXT, pay_period TEXT, weekly_mxn NUMERIC(14,2), offer_location TEXT, target_profile TEXT,",
         "    verbatim_quote TEXT, paraphrase TEXT, scheme TEXT, criminal_recruitment BOOLEAN NOT NULL,",
         "    outcome TEXT, confidence TEXT NOT NULL, n_sources INTEGER NOT NULL);",
         "CREATE TABLE IF NOT EXISTS press_offer_sources (",
         "    offer_uid TEXT REFERENCES press_offers(offer_uid), article_key TEXT REFERENCES press_articles(article_key),",
         "    PRIMARY KEY (offer_uid, article_key));",
         "CREATE TABLE IF NOT EXISTS press_offer_flags (",
         "    offer_uid TEXT REFERENCES press_offers(offer_uid), flag TEXT NOT NULL, track CHAR(1) NOT NULL CHECK (track IN ('A','B')),",
         "    PRIMARY KEY (offer_uid, flag));", ""]
    arts = {}
    for s in sources:
        arts.setdefault(akey(s["url"]), s)
    L.append("INSERT INTO press_articles VALUES\n" + ",\n".join(
        f" ({q(k)}, {q(s['url'])}, {q(s['outlet'])}, {q(s['published'])})" for k, s in arts.items()) + "\nON CONFLICT DO NOTHING;\n")
    rows, flags = [], []
    for o in offers:
        iso3 = o["countries"].split(";")[0] if o["countries"] else ""
        if "MEX" in o["countries"]:
            iso3 = "MEX"
        plat = PLATFORM.get(o["platform"])
        weekly = o["pay_amount"] if o["pay_currency"] == "MXN" and o["pay_period"] == "semanal" else ""
        rows.append(
            f" ({q(o['offer_uid'])}, {f'(SELECT country_code FROM countries WHERE country_iso3 = {q(iso3)})' if iso3 else 'NULL'}, "
            f"{f'(SELECT platform_id FROM platforms WHERE platform_name = {q(plat)})' if plat else 'NULL'}, "
            f"{q(o['job_title'])}, {o['pay_amount'] or 'NULL'}, {q(o['pay_currency'])}, {q(o['pay_period'])}, {weekly or 'NULL'}, "
            f"{q(o['offer_location'])}, {q(o['target_profile'])}, {q(o['verbatim_quote'])}, {q(o['paraphrase'])}, "
            f"{q(o['scheme'] if o['scheme'] in SCHEMES else '')}, {'TRUE' if o['criminal_recruitment'] == 'True' else 'FALSE'}, "
            f"{q(o['outcome'])}, {q(o['confidence'])}, {int(o['n_sources'])})")
        for f_ in filter(None, o["type_a_flags"].split(";")):
            flags.append(f" ({q(o['offer_uid'])}, {q(f_)}, 'A')")
        for f_ in filter(None, o["type_b_flags"].split(";")):
            flags.append(f" ({q(o['offer_uid'])}, {q(f_)}, 'B')")
    L.append("INSERT INTO press_offers VALUES\n" + ",\n".join(rows) + "\nON CONFLICT DO NOTHING;\n")
    L.append("INSERT INTO press_offer_sources VALUES\n" + ",\n".join(
        f" ({q(s['offer_uid'])}, {q(akey(s['url']))})" for s in sources) + "\nON CONFLICT DO NOTHING;\n")
    L.append("INSERT INTO press_offer_flags VALUES\n" + ",\n".join(flags) + "\nON CONFLICT DO NOTHING;\n")
    SQL.write_text("\n".join(L), encoding="utf-8")
    return len(offers), len(arts), len(flags)


def m(mid, target, source):
    return f"mappingId   {mid}\ntarget      {target}\nsource      {source}\n"


def build_obda():
    o = f"<{D}/press-offer/{{offer_uid}}>"
    T = "ramona.press_offers"
    B = [
        m("M-Press-Offer", f"{o} a :JobOffer ; :extractionConfidence {{confidence}}^^xsd:string .",
          f"SELECT offer_uid, confidence FROM {T}"),
        m("M-Press-Role", f"{o} :offeredRole {{job_title}}^^xsd:string .", f"SELECT offer_uid, job_title FROM {T} WHERE job_title IS NOT NULL"),
        m("M-Press-Location", f"{o} :offeredLocation {{offer_location}}^^xsd:string .", f"SELECT offer_uid, offer_location FROM {T} WHERE offer_location IS NOT NULL"),
        m("M-Press-Country", f"{o} :inCountry <{D}/country/{{country_code}}> .", f"SELECT offer_uid, country_code FROM {T} WHERE country_code IS NOT NULL"),
        m("M-Press-Platform", f"{o} :postedVia <{D}/platform/{{platform_id}}> .", f"SELECT offer_uid, platform_id FROM {T} WHERE platform_id IS NOT NULL"),
        m("M-Press-Pay", f"{o} :offerPayAmount {{pay_amount}}^^xsd:decimal ; :offerPayCurrency {{pay_currency}}^^xsd:string .",
          f"SELECT offer_uid, pay_amount, pay_currency FROM {T} WHERE pay_amount IS NOT NULL AND pay_currency IS NOT NULL"),
        m("M-Press-PayPeriod", f"{o} :offerPayPeriod {{pay_period}}^^xsd:string .", f"SELECT offer_uid, pay_period FROM {T} WHERE pay_period IS NOT NULL"),
        m("M-Press-WeeklyMXN", f"{o} :offeredSalaryMXN {{weekly_mxn}}^^xsd:decimal .", f"SELECT offer_uid, weekly_mxn FROM {T} WHERE weekly_mxn IS NOT NULL"),
        m("M-Press-Target", f"{o} :offerTargetProfile {{target_profile}}^^xsd:string .", f"SELECT offer_uid, target_profile FROM {T} WHERE target_profile IS NOT NULL"),
        m("M-Press-Quote", f"{o} :offerVerbatimQuote {{verbatim_quote}}^^xsd:string .", f"SELECT offer_uid, verbatim_quote FROM {T} WHERE verbatim_quote IS NOT NULL"),
        m("M-Press-Summary", f"{o} :offerSummary {{paraphrase}}^^xsd:string .", f"SELECT offer_uid, paraphrase FROM {T} WHERE paraphrase IS NOT NULL"),
        m("M-Press-Outcome", f"{o} :offerOutcome {{outcome}}^^xsd:string .", f"SELECT offer_uid, outcome FROM {T} WHERE outcome IS NOT NULL"),
        m("M-Press-Criminal", f"{o} a :CriminalRecruitmentOffer .", f"SELECT offer_uid FROM {T} WHERE criminal_recruitment"),
        m("M-Press-Article", f"<{D}/press/{{article_key}}> a :PressArticle ; :sourceUrl {{url}}^^xsd:string ; :sourceOutlet {{outlet}}^^xsd:string .",
          "SELECT article_key, url, outlet FROM ramona.press_articles"),
        m("M-Press-Source", f"{o} :offerDocumentedIn <{D}/press/{{article_key}}> .", "SELECT offer_uid, article_key FROM ramona.press_offer_sources"),
        m("M-Press-Flag", f"{o} :hasRedFlag <{D}/press-offer/{{offer_uid}}/flag/{{flag}}> .", "SELECT offer_uid, flag FROM ramona.press_offer_flags"),
        m("M-Press-FlagType", f"<{D}/press-offer/{{offer_uid}}/flag/{{flag}}> :flagType {{flag}}^^xsd:string .", "SELECT offer_uid, flag FROM ramona.press_offer_flags"),
        m("M-Press-FlagA", f"<{D}/press-offer/{{offer_uid}}/flag/{{flag}}> a :ClassicRedFlag .", "SELECT offer_uid, flag FROM ramona.press_offer_flags WHERE track = 'A'"),
        m("M-Press-FlagB", f"<{D}/press-offer/{{offer_uid}}/flag/{{flag}}> a :CredibleLethalRedFlag .", "SELECT offer_uid, flag FROM ramona.press_offer_flags WHERE track = 'B'"),
    ]
    for sc in SCHEMES:
        B.append(m(f"M-Press-Scheme-{sc}", f"{o} :exhibitsFraudScheme <{D}/press-offer/{{offer_uid}}/scheme> .", f"SELECT offer_uid FROM {T} WHERE scheme = '{sc}'"))
        B.append(m(f"M-Press-SchemeType-{sc}", f"<{D}/press-offer/{{offer_uid}}/scheme> a :{sc} .", f"SELECT offer_uid FROM {T} WHERE scheme = '{sc}'"))
    text = OBDA.read_text(encoding="utf-8")
    text = re.sub(r"mappingId\s+M-Press-[^\n]*\ntarget[^\n]*\nsource[^\n]*\n\n?", "", text)
    i = text.rstrip().rfind("]]")
    OBDA.write_text(text[:i].rstrip() + "\n\n" + "\n".join(B) + "\n]]\n", encoding="utf-8")
    return len(B)


if __name__ == "__main__":
    n, a, f = build_sql()
    print(f"SQL: {n} ofertas reales, {a} notas, {f} senales -> {SQL.relative_to(ROOT)}")
    print(f"OBDA: {build_obda()} mapeos M-Press-* -> {OBDA.relative_to(ROOT)}")
