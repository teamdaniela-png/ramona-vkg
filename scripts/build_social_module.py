#!/usr/bin/env python3
"""
Modulo de reclutamiento en redes (RATR-O v1.9): SQL + mapeos OBDA.

Lee  data/lexicon/tiktok_reclutamiento_lexicon.csv
     data/synthetic/tiktok_reclutamiento_sintetico.csv
Escribe db/11_social_media_module.sql
        los mapeos M-Social-* y M-Lexicon-* dentro de mappings/ramona.obda (los reemplaza si ya existen)

Uso: python3 scripts/build_social_module.py   (correr despues de build_tiktok_synthetic.py)
"""
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEX = ROOT / "data/lexicon/tiktok_reclutamiento_lexicon.csv"
SYN = ROOT / "data/synthetic/tiktok_reclutamiento_sintetico.csv"
SQL = ROOT / "db/11_social_media_module.sql"
OBDA = ROOT / "mappings/ramona.obda"

D = "https://w3id.org/ratr-o/data"
ONT = "https://w3id.org/ratr-o#"

SIGNAL_CLASS = {
    "codigo_grupo": "GroupCodeSignal", "emoji_grupo": "GroupEmojiSignal",
    "llamado_privado": "PrivateChannelCallSignal", "pago_semanal_alto": "HighWeeklyPaySignal",
    "apela_familia": "FamilyAppealSignal", "menciona_edad_menor": "MinorAgeMentionSignal",
    "invita_mujeres": "WomenInvitationSignal", "alcance_nacional": "NationalReachSignal",
    "hashtag_reclutamiento": "RecruitmentHashtagSignal", "fatalismo": "FatalismSignal",
}


def q(v):
    if v is None or v == "":
        return "NULL"
    return "'" + str(v).replace("'", "''") + "'"


def b(v):
    return "TRUE" if v else "FALSE"


def build_sql():
    lex = list(csv.DictReader(open(LEX, encoding="utf-8")))
    syn = list(csv.DictReader(open(SYN, encoding="utf-8")))
    out = [
        "-- RATR-O v1.9 social-media criminal-recruitment module.",
        "-- GENERATED by scripts/build_social_module.py. Do not edit by hand.",
        "-- Lexicon: Colmex SVP 2025 'Del scroll al jale'. Items: SYNTHETIC (data/synthetic/README.md).",
        "SET search_path TO ramona, public;",
        "",
        "CREATE TABLE IF NOT EXISTS lexicon_terms (",
        "    term_id          TEXT PRIMARY KEY,",
        "    term_text        TEXT NOT NULL,",
        "    pattern          TEXT NOT NULL,",
        "    category         TEXT NOT NULL,",
        "    is_verbatim      BOOLEAN NOT NULL,",
        "    source_location  TEXT",
        ");",
        "",
        "CREATE TABLE IF NOT EXISTS social_items (",
        "    item_id          TEXT PRIMARY KEY,",
        "    item_kind        TEXT NOT NULL CHECK (item_kind IN ('post','comment')),",
        "    label            TEXT NOT NULL,",
        "    item_text        TEXT NOT NULL,",
        "    platform_id      INTEGER REFERENCES platforms(platform_id),",
        "    posted_at        TIMESTAMP,",
        "    hashtags         TEXT,",
        "    audio_hint       TEXT,",
        "    visual_hint      TEXT,",
        "    weekly_pay_mxn   NUMERIC(10,2),",
        "    cond_nr          BOOLEAN NOT NULL DEFAULT FALSE,",
        "    cond_ecc         BOOLEAN NOT NULL DEFAULT FALSE,",
        "    cond_avc         BOOLEAN NOT NULL DEFAULT FALSE,",
        "    cond_a           BOOLEAN NOT NULL DEFAULT FALSE,",
        "    is_synthetic     BOOLEAN NOT NULL",
        ");",
        "",
        "CREATE TABLE IF NOT EXISTS social_item_signals (",
        "    item_id TEXT REFERENCES social_items(item_id),",
        "    signal  TEXT NOT NULL,",
        "    PRIMARY KEY (item_id, signal)",
        ");",
        "",
        "CREATE TABLE IF NOT EXISTS social_item_terms (",
        "    item_id TEXT REFERENCES social_items(item_id),",
        "    term_id TEXT REFERENCES lexicon_terms(term_id),",
        "    PRIMARY KEY (item_id, term_id)",
        ");",
        "",
        "INSERT INTO lexicon_terms VALUES",
    ]
    out.append(",\n".join(
        f" ({q(t['term_id'])}, {q(t['termino'])}, {q(t['patron_regex'])}, {q(t['categoria'])}, "
        f"{b(t['tipo'] == 'verbatim_colmex')}, {q(('p. ' + t['pagina'] + '; ' if t['pagina'] else '') + t['elemento'])})"
        for t in lex) + "\nON CONFLICT DO NOTHING;")
    out.append("")
    out.append("INSERT INTO social_items VALUES")
    rows, sigs, terms = [], [], []
    for r in syn:
        conds = set(filter(None, r["colmex_conditions"].split(";")))
        kind = "comment" if r["content_type"] == "comentario" else "post"
        weekly = r["promised_salary_amount"] if r["promised_salary_period"] == "semanal" else ""
        rows.append(
            f" ({q(r['offer_id'])}, '{kind}', {q(r['label'])}, {q(r['offer_text'])}, "
            f"(SELECT platform_id FROM platforms WHERE platform_type = 'tiktok' LIMIT 1), "
            f"{q(r['first_contact_at'].replace('T', ' '))}, {q(r['hashtags'])}, {q(r['audio_hint'])}, "
            f"{q(r['visual_hint'])}, {weekly or 'NULL'}, {b('nr' in conds)}, {b('ecc' in conds)}, "
            f"{b('avc' in conds)}, {b('a' in conds)}, {b(r['synthetic'] == 'true')})")
        for s in filter(None, r["crim_flags"].split(";")):
            sigs.append(f" ({q(r['offer_id'])}, {q(s)})")
        for t in filter(None, r["lexicon_term_ids"].split(";")):
            terms.append(f" ({q(r['offer_id'])}, {q(t)})")
    out.append(",\n".join(rows) + "\nON CONFLICT DO NOTHING;\n")
    out.append("INSERT INTO social_item_signals VALUES\n" + ",\n".join(sigs) + "\nON CONFLICT DO NOTHING;\n")
    out.append("INSERT INTO social_item_terms VALUES\n" + ",\n".join(terms) + "\nON CONFLICT DO NOTHING;\n")
    SQL.write_text("\n".join(out), encoding="utf-8")
    return len(lex), len(syn), len(sigs), len(terms)


def m(mid, target, source):
    return f"mappingId   {mid}\ntarget      {target}\nsource      {source}\n"


def build_obda():
    it = f"<{D}/social/{{item_id}}>"
    blocks = [
        m("M-Social-Post", f"{it} a :SocialMediaPost ; :itemText {{item_text}}^^xsd:string ; :itemPostedAt {{posted_at}}^^xsd:dateTime ; :itemIsSynthetic {{is_synthetic}}^^xsd:boolean ; :itemPostedOn <{D}/platform/{{platform_id}}> .",
          "SELECT item_id, item_text, posted_at, is_synthetic, platform_id FROM ramona.social_items WHERE item_kind = 'post'"),
        m("M-Social-Comment", f"{it} a :SocialMediaComment ; :itemText {{item_text}}^^xsd:string ; :itemPostedAt {{posted_at}}^^xsd:dateTime ; :itemIsSynthetic {{is_synthetic}}^^xsd:boolean ; :itemPostedOn <{D}/platform/{{platform_id}}> .",
          "SELECT item_id, item_text, posted_at, is_synthetic, platform_id FROM ramona.social_items WHERE item_kind = 'comment'"),
        m("M-Social-Hashtags", f"{it} :itemHashtags {{hashtags}}^^xsd:string .",
          "SELECT item_id, hashtags FROM ramona.social_items WHERE hashtags IS NOT NULL"),
        m("M-Social-Audio", f"{it} :audioDescription {{audio_hint}}^^xsd:string .",
          "SELECT item_id, audio_hint FROM ramona.social_items WHERE item_kind = 'post' AND audio_hint IS NOT NULL"),
        m("M-Social-Visual", f"{it} :visualDescription {{visual_hint}}^^xsd:string .",
          "SELECT item_id, visual_hint FROM ramona.social_items WHERE item_kind = 'post' AND visual_hint IS NOT NULL"),
        m("M-Social-WeeklyPay", f"{it} :promisedWeeklyPayMXN {{weekly_pay_mxn}}^^xsd:decimal .",
          "SELECT item_id, weekly_pay_mxn FROM ramona.social_items WHERE item_kind = 'post' AND weekly_pay_mxn IS NOT NULL"),
        m("M-Social-SelfApplication", f"{it} a :SelfApplicationComment .",
          "SELECT item_id FROM ramona.social_items WHERE label = 'autopostulacion'"),
        m("M-Social-RecruiterReply", f"{it} a :RecruiterReplyComment .",
          "SELECT item_id FROM ramona.social_items WHERE label = 'respuesta_reclutador'"),
        # Condiciones QCA (una clase por condicion)
        m("M-Social-Cond-NR", f"{it} a :DirectRecruitmentPost .",
          "SELECT item_id FROM ramona.social_items WHERE item_kind = 'post' AND cond_nr"),
        m("M-Social-Cond-ECC", f"{it} a :CriminalCultureExaltationPost .",
          "SELECT item_id FROM ramona.social_items WHERE item_kind = 'post' AND cond_ecc"),
        m("M-Social-Cond-AVC", f"{it} a :CriminalLifeAspirationPost .",
          "SELECT item_id FROM ramona.social_items WHERE item_kind = 'post' AND cond_avc"),
        m("M-Social-Cond-A", f"{it} a :AcousticFramingPost .",
          "SELECT item_id FROM ramona.social_items WHERE item_kind = 'post' AND cond_a"),
        # Direccion suficiente de los relatos: conjuncion que OWL 2 QL no puede expresar
        m("M-Social-Story-Enrol", f"{it} a :EnrolInCrimeStoryPost .",
          "SELECT item_id FROM ramona.social_items WHERE item_kind = 'post' AND cond_nr AND cond_ecc"),
        m("M-Social-Story-Emotional", f"{it} a :EmotionalConnectionStoryPost .",
          "SELECT item_id FROM ramona.social_items WHERE item_kind = 'post' AND cond_nr AND cond_a"),
        m("M-Social-Story-Belico", f"{it} a :BelicoStoryPost .",
          "SELECT item_id FROM ramona.social_items WHERE item_kind = 'post' AND cond_ecc AND cond_a AND cond_avc"),
        m("M-Lexicon-Term", f"<{D}/lexicon/{{term_id}}> a :LexiconTerm ; :lexiconTermText {{term_text}}^^xsd:string ; :lexiconPattern {{pattern}}^^xsd:string ; :lexiconCategory {{category}}^^xsd:string ; :lexiconIsVerbatim {{is_verbatim}}^^xsd:boolean .",
          "SELECT term_id, term_text, pattern, category, is_verbatim FROM ramona.lexicon_terms"),
        m("M-Lexicon-Source", f"<{D}/lexicon/{{term_id}}> :termDocumentedIn <{ONT}ColmexScrollAlJale2025> ; :lexiconSourceLocation {{source_location}}^^xsd:string .",
          "SELECT term_id, source_location FROM ramona.lexicon_terms WHERE is_verbatim"),
        m("M-Social-Term", f"{it} :itemMatchesTerm <{D}/lexicon/{{term_id}}> .",
          "SELECT item_id, term_id FROM ramona.social_item_terms"),
    ]
    for sig, cls in SIGNAL_CLASS.items():
        src = f"SELECT item_id FROM ramona.social_item_signals WHERE signal = '{sig}'"
        blocks.append(m(f"M-Social-Signal-{cls}", f"{it} :itemHasSignal <{D}/social/{{item_id}}/signal/{sig}> .", src))
        blocks.append(m(f"M-Social-SignalType-{cls}", f"<{D}/social/{{item_id}}/signal/{sig}> a :{cls} .", src))
    # Ontop no admite comentarios dentro de [[ ]]: se identifican por prefijo de mappingId
    text = OBDA.read_text(encoding="utf-8")
    text = re.sub(r"mappingId\s+M-(Social|Lexicon)-[^\n]*\ntarget[^\n]*\nsource[^\n]*\n\n?", "", text)
    i = text.rstrip().rfind("]]")
    text = text[:i].rstrip() + "\n\n" + "\n".join(blocks) + "\n]]\n"
    OBDA.write_text(text, encoding="utf-8")
    return len(blocks)


if __name__ == "__main__":
    nl, ns, nsig, nt = build_sql()
    nm = build_obda()
    print(f"SQL: {nl} terminos, {ns} items, {nsig} senales, {nt} coincidencias -> {SQL.relative_to(ROOT)}")
    print(f"OBDA: {nm} mapeos agregados -> {OBDA.relative_to(ROOT)}")
